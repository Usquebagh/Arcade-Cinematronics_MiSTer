"""Generate Armor Attack tread VCO data from its resistor network and pinned MAME fit."""
import argparse,math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
    lines=['// Generated by tools/prepare_armora_sound.py; circuit 72-11141-02, CC0 MAME fit.']
    lines+=['function automatic [15:0] tread_target(input [1:0] bits);','    case(bits)']
    for bits in range(4):
        # IC13 QD/QC; the wired-NOR output enables the third grounding switch.
        conductance=1/51000+1/1500000
        if not (bits&2):conductance+=1/430000
        if not (bits&1):conductance+=1/1500000
        if bits:conductance+=1/390000
        volts=(15/51000)/conductance
        level=round((volts-11.5)/3.1*65535)
        assert 0<=level<=65535
        lines.append(f"        2'd{bits}: tread_target=16'd{level}; // {volts:.5f} V")
    lines+=['    endcase','endfunction','function automatic [23:0] tread_clock(input [4:0] level);','    case(level)']
    for n in range(32):
        v=11.5+3.1*n/31
        hp=.000000646112*v**3-.0000215063*v**2+.000242010*v-.000908469
        hz=1/(2*max(.000001,min(.1,hp)))
        inc=round(hz*2**24/96000)
        assert 0<inc<2**24
        lines.append(f"        5'd{n}: tread_clock=24'd{inc}; // {hz:.2f} Hz")
    lines+=['    endcase','endfunction']
    return '\n'.join(lines)+'\n'
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    dest=ROOT/'rtl/sound/armora_clocks.svh';text=generate()
    if a.check:
        if dest.read_text()!=text:raise SystemExit('Stale Armor Attack oscillator table')
    else:dest.write_bytes(text.encode())
    print('PASS: Armor Attack resistor-DAC targets and fitted tread VCO table')
if __name__=='__main__':main()
